'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const XLSX = require('xlsx');
const { buildCourseRoadmap } = require('./lib/course-roadmap.cjs');

const root = path.resolve(__dirname, '..');
const source = 'content/source-intake/workbooks/diaspora_10000_content_master.xlsx';
const bytes = fs.readFileSync(path.join(root, source));
const workbook = XLSX.read(bytes, { type: 'buffer' });
function rows(name) {
  if (!workbook.Sheets[name]) throw new Error(`Missing sheet: ${name}`);
  return XLSX.utils.sheet_to_json(workbook.Sheets[name], { defval: '' });
}
const courses = buildCourseRoadmap({
  languages: rows('Languages'), units: rows('Unit_Roadmap'),
  lessons: rows('Lessons'), vocabulary: rows('Vocabulary_Master'),
});
const result = { source, sourceSha256: crypto.createHash('sha256').update(bytes).digest('hex'), courses };
const output = '// Generated by npm run content:roadmap. Do not edit manually.\nmodule.exports = '
  + JSON.stringify(result) + ';\n';
const target = path.join(root, 'src/data/generatedCourseRoadmap.cjs');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw new Error('Course roadmap is stale. Run npm run content:roadmap.');
} else {
  fs.writeFileSync(target, output);
}
console.log(`Verified ${courses.length} course roadmaps, ${courses.reduce((sum, course) => sum + course.units.length, 0)} units.`);
