#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const XLSX = require('xlsx');
const { buildMasterPreview } = require('./lib/master-preview-curriculum.cjs');
const root = path.resolve(__dirname, '..');
const workbookPath = 'content/source-intake/workbooks/diaspora_10000_content_master.xlsx';
const candidatePath = 'content/master-preview/igbo-greetings.json';
const outputPath = path.join(root, 'src/data/generatedMasterPreview.cjs');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');

function generate() {
  const candidateBytes = fs.readFileSync(path.join(root, candidatePath));
  const manifest = JSON.parse(candidateBytes);
  const sourcePath = path.resolve(root, manifest.sourcePath);
  const allowedRoot = `${path.join(root, 'content/source-intake/quizlet/raw')}${path.sep}`;
  if (!sourcePath.startsWith(allowedRoot) || !fs.realpathSync(sourcePath).startsWith(allowedRoot)) {
    throw new Error('Translation source must be inside the raw intake directory.');
  }
  const sourceBytes = fs.readFileSync(sourcePath);
  if (hash(sourceBytes) !== manifest.sourceSha256) throw new Error('Translation source checksum changed. Reconcile source mappings before rebuilding.');
  const referenceRoot = `${path.join(root, 'content/source-intake/research')}${path.sep}`;
  const referenceSources = {};
  const referenceMeta = [];
  for (const referenceManifest of manifest.referenceSources || []) {
    const referencePath = path.resolve(root, referenceManifest.path);
    if (!referencePath.startsWith(referenceRoot) || !fs.realpathSync(referencePath).startsWith(referenceRoot)) {
      throw new Error('Reference evidence must be inside the research intake directory.');
    }
    const bytes = fs.readFileSync(referencePath);
    if (hash(bytes) !== referenceManifest.sha256) throw new Error(`Reference evidence checksum changed: ${referenceManifest.id}`);
    const reference = JSON.parse(bytes);
    if (reference.id !== referenceManifest.id || referenceSources[reference.id]) throw new Error(`Invalid or duplicate reference evidence: ${referenceManifest.id}`);
    referenceSources[reference.id] = reference;
    referenceMeta.push({ id: reference.id, path: referenceManifest.path, sha256: hash(bytes) });
  }
  const workbookBytes = fs.readFileSync(path.join(root, workbookPath));
  const workbook = XLSX.read(workbookBytes);
  const rows = sheet => XLSX.utils.sheet_to_json(workbook.Sheets[sheet], { defval: '' });
  const source = XLSX.read(sourceBytes.toString('utf8'), { type: 'string' });
  const curriculum = buildMasterPreview({ languages: rows('Languages'), units: rows('Unit_Roadmap'),
    lessons: rows('Lessons'), vocabulary: rows('Vocabulary_Master') }, manifest,
  XLSX.utils.sheet_to_json(source.Sheets[source.SheetNames[0]], { defval: '' }), referenceSources);
  const data = { meta: { schemaVersion: 1, sourceWorkbook: workbookPath, sourceSha256: hash(workbookBytes),
    candidatePath, candidateSha256: hash(candidateBytes), referenceSources: referenceMeta }, ...curriculum };
  const text = `// Generated by scripts/generate-master-preview.cjs. Do not edit.\n'use strict';\n\nconst GENERATED_MASTER_PREVIEW = ${JSON.stringify(data, null, 2)};\n\nmodule.exports = { GENERATED_MASTER_PREVIEW };\n`;
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== text) throw new Error('Master preview is stale. Run npm run content:master:build.');
  } else fs.writeFileSync(outputPath, text);
  console.log(`Master preview verified: ${curriculum.courses.length} draft course, ${curriculum.topics.length} lessons, ${curriculum.lessonSteps.length} exercises; native review pending.`);
}

try { generate(); } catch (error) { console.error(error.message); process.exitCode = 1; }
